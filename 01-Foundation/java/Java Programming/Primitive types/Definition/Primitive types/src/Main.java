public class Main {
   public static void main(String[] args) {
      boolean boolVar = true;
      System.out.println("boolVar value is " + boolVar);

      char charVar = 'a';
      System.out.println("charVar value is " + charVar);

      byte byteVar = Byte.MAX_VALUE;
      System.out.println("byteVar value is " + byteVar);

      short shortVar = Short.MIN_VALUE;
      System.out.println("shortVar value is " + shortVar);

      int intVar = Integer.MAX_VALUE;
      System.out.println("intVar value is " + intVar);

      long longVar = Long.MIN_VALUE;
      System.out.println("longVar value is " + longVar);

      float floatVar = Float.MAX_VALUE;
      System.out.println("floatVar value is " + floatVar);

      double doubleVar = Double.MAX_VALUE;
      System.out.println("doubleVar value is " + doubleVar);
   }
}